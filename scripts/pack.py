#!/usr/bin/env python3
"""Build the packed fork with Python 3 and the bundled Rhino compressor.

With no module arguments, replace packed/MochiKit/MochiKit.js. With module
arguments, write a custom bundle to stdout in the supplied dependency order.
Use --check to verify the checked-in full bundle without changing it.
"""

import argparse
import os
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'packed' / 'MochiKit' / 'MochiKit.js'
HEADER = '''/***

    MochiKit.MochiKit {version} : PACKED VERSION (JasonBunting fork)

    THIS FILE IS AUTOMATICALLY GENERATED. Edit the source in MochiKit/,
    then regenerate with: python scripts/pack.py

    Fork: https://github.com/JasonBunting/mochikit
    Original project: https://github.com/mochi/mochikit
    License: see LICENSE.txt (MIT or Academic Free License 2.1).

    (c) 2005 Bob Ippolito. All rights Reserved.

***/

'''


def build(modules):
    loader = (ROOT / 'MochiKit' / 'MochiKit.js').read_text(encoding='utf-8')
    version = re.search(r'MochiKit.MochiKit.VERSION\s*=\s*[\'"]([^\'"]+)', loader).group(1)
    module_list = re.search(r'MochiKit.MochiKit.SUBMODULES\s*=\s*\[([^\]]+)', loader).group(1)
    available = re.findall(r'[\'"]([^\'"]+)[\'"]', module_list)
    for module in modules:
        if module not in available:
            raise ValueError('Unknown module: ' + module)
    source = '\n'.join(
        (ROOT / 'MochiKit' / (module + '.js')).read_text(encoding='utf-8')
        for module in (modules or available)
    )
    # Close the scratch file before Java opens it (required on Windows).
    with tempfile.TemporaryDirectory(prefix='mochikit-pack-') as scratch:
        source_path = Path(scratch) / 'source.js'
        source_path.write_text(source, encoding='utf-8', newline='\n')
        result = subprocess.run(
            ['java', '-Dfile.encoding=UTF-8', '-jar',
             str(ROOT / 'scripts' / 'custom_rhino.jar'), '-c', str(source_path)],
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True,
        )
    if not result.stdout.strip():
        raise ValueError('Rhino produced an empty bundle')
    compressed = result.stdout.decode('utf-8').replace('\r\n', '\n').rstrip('\r\n')
    return (HEADER.format(version=version) + compressed + '\n').encode('utf-8')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the full bundle is out of date')
    parser.add_argument('modules', nargs='*', help='optional module names in dependency order')
    args = parser.parse_args(argv)
    if args.check and args.modules:
        parser.error('--check cannot be combined with custom modules')
    try:
        packed = build(args.modules)
        if args.check:
            # Git may use CRLF in a Windows checkout; this is not staleness.
            if not OUTPUT.exists() or OUTPUT.read_bytes().replace(b'\r\n', b'\n') != packed:
                print('Packed bundle is out of date. Run: python scripts/pack.py', file=sys.stderr)
                return 1
            print('Packed bundle is up to date.')
        elif args.modules:
            sys.stdout.buffer.write(packed)
        else:
            # Never truncate a working bundle if compilation or writing fails.
            temp_path = None
            try:
                with tempfile.NamedTemporaryFile(dir=OUTPUT.parent, suffix='.tmp', delete=False) as out:
                    temp_path = Path(out.name)
                    out.write(packed)
                os.replace(temp_path, OUTPUT)
            finally:
                if temp_path is not None and temp_path.exists():
                    temp_path.unlink()
            print('Updated ' + str(OUTPUT))
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        print('Packing failed: ' + str(error), file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.decode('utf-8', errors='replace'), file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
